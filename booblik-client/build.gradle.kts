/*
 * Клиент и общий кодек, отдельно от сервера.
 *
 * Разделение не косметическое. Во-первых, потребителю библиотеки незачем тянуть селектор,
 * сессию и брокер — он ими не пользуется, но собирает и грузит. Во-вторых, это ровно та работа,
 * которую пришлось бы сделать при переходе на Kotlin Multiplatform (решение Р8): непереносимое
 * в клиенте перечислимо — сокеты, `ByteBuffer`, два примитива из `java.util.concurrent` и
 * `CRC32C`, — и теперь оно лежит в одном месте, а не размазано по модулю с сервером.
 *
 * Кодек живёт здесь, а не в сервере, потому что он **общий**: обе стороны обязаны понимать
 * одинаково, и модуль, который видят обе, — единственное место, где это утверждение проверяется
 * компилятором.
 */
